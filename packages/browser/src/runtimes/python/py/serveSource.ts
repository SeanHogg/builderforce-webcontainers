/**
 * `bfwc/serve.py`: serve an ASGI or WSGI app request-driven. The runtime calls
 * `Server.handle` once per request that reaches the service's virtual port;
 * the app answers through a JavaScript responder: `head(status, headersJson)`,
 * `chunk(bytes)` as the body is written (returning a promise while the reader
 * is behind — an ASGI `send` waits on it), `end(error)` once. ASGI apps get the
 * lifespan protocol (startup on start, shutdown on close) when they speak it;
 * an app that returns or raises on the lifespan scope does not (uvicorn's
 * "auto"). A program can ask to be served (`ServeRequested`, raised by the
 * runtime's uvicorn stand-in) instead of being named on the command line.
 */
