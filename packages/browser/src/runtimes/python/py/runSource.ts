/**
 * `bfwc/run.py`: run a script, `-c` code or a `-m` module the way `python`
 * does, and return its exit code (`SystemExit` honoured, an uncaught exception
 * printed as a traceback and exit 1, `atexit` handlers run). A program that
 * asks to serve an app (`uvicorn.run(app)`, the runtime's stand-in) returns
 * `"serve"` instead: the runtime then serves it (`bfwc.serve.start_requested`).
 * Also the process bootstrap: environment, working directory, line-buffered
 * output, and no bytecode files in the project.
 */
