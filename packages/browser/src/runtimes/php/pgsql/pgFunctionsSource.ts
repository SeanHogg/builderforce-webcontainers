/**
 * The `pgsql` extension's functions (`pg_connect`, `pg_query`,
 * `pg_query_params`, `pg_prepare`/`pg_execute`, `pg_fetch_*`, `pg_field_*`,
 * `pg_escape_*` …) and its `PGSQL_*` constants, defined in PHP on the
 * runtime's wire client (wireSource.ts; state and classes in
 * pgSupportSource.ts) because php-wasm has no `pgsql` extension. Loaded by the
 * auto-prepended script only when `pg_connect` does not exist.
 *
 * As the extension: values come back as text (`'t'`/`'f'` for booleans) or
 * null; booleans are sent as `'1'`/`''`; `pg_prepare` parses a named statement
 * on the server; `pg_connect` reuses an open connection with the same
 * connection string unless `PGSQL_CONNECT_FORCE_NEW`; `pg_fetch_object` sets
 * properties before the constructor runs; a two-argument `pg_fetch_result`
 * reads the next row; `pg_fetch_all` leaves the cursor; `PGSQL_BOTH` keys
 * interleave; a closed or missing connection throws the extension's `Error`,
 * a bad field a `ValueError`; a connection-class failure (SQLSTATE 08, 57P)
 * leaves the connection `PGSQL_CONNECTION_BAD`.
 *
 * Differences: failures warn with `E_USER_WARNING` (PHP code cannot raise
 * `E_WARNING`), with the extension's message; a failed query returns false, so
 * `pg_result_error` is always '' and `pg_result_error_field` null;
 * `pg_set_error_verbosity` is recorded but messages keep one form. Absent:
 * `pg_meta_data`, `pg_insert`/`pg_update`/`pg_select`/`pg_delete`/`pg_convert`,
 * asynchronous `pg_send_*`/`pg_get_result`, COPY (`pg_copy_*`, `pg_put_line`),
 * large objects (`pg_lo_*`), `pg_get_notify`, `pg_trace`, `pg_socket`.
 */
